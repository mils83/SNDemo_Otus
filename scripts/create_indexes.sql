-- ============================================================================
-- ДЗ №6 «Производительность индексов»: индексы для поиска анкет по префиксу
-- имени и фамилии (first_name LIKE 'Aн%' AND last_name LIKE 'Ив%').
--
-- Почему составной btree по (first_name, last_name) с классом операторов
-- varchar_pattern_ops:
--   1) Составной индекс обслуживает ОБА условия префикса: по ведущей колонке
--      first_name выбирается диапазон 'Ан' >= col < 'АнЁ...', а условие на
--      last_name фильтруется вторым ключом индекса без обращения к heap.
--   2) *_pattern_ops нужен потому, что в не-C локали btree-индекс НЕ
--      используется для LIKE 'префикс%' (сравнение строк в локали несовместимо
--      с посимвольным сравнением паттерна). varchar_pattern_ops хранит
--      посимвольный порядок и делает префиксную выборку через
--      '>= prefix' AND '<  prefix_increment'.
--   3) CONCURRENTLY — построение блокирует только запись, а не чтение
--      ( индекс строится поверх уже работающей таблицы пользователей).
--   4) Сортировка ORDER BY id здесь не обслуживается индексом (выдача всегда
--      ограничена LIMIT'ом, TOP-N сортировка ≤ LIMIT + число строк диапазона
--      — дешёвая), поэтому включать id в индекс не требуется.
--
-- Применение: psql -U postgres -d social_network -f scripts/create_indexes.sql
-- ============================================================================

CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_users_first_name_last_name_pattern
    ON users (first_name varchar_pattern_ops, last_name varchar_pattern_ops);

ANALYZE users;
